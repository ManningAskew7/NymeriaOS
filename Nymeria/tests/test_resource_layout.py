def _tool_json(tool_id: str, description: str = "demo tool") -> str:
    return json.dumps(
        {
            "id": tool_id,
            "name": tool_id,
            "description": description,
            "implementation_type": "http",
            "http_config": {"url": "https://example.com", "method": "GET"},
        }
    )


def _make_loader(tmp_path):
    from nymeria.core.custom_tools import CustomToolLoader

    loader = CustomToolLoader(tools_dir=tmp_path)
    loader.EXTERNAL_REFRESH_INTERVAL_SECONDS = 0.0
    loader.load_all()
    return loader


def test_custom_tools_hot_load_add_edit_remove(tmp_path):
    loader = _make_loader(tmp_path)
    assert loader.get_definition("ext_demo") is None

    # Externally created file appears without load_all.
    (tmp_path / "ext_demo.json").write_text(_tool_json("ext_demo"), encoding="utf-8")
    defn = loader.get_definition("ext_demo")
    assert defn is not None and defn.description == "demo tool"
    assert loader.drain_registry_sync() == {"ext_demo"}
    assert loader.drain_registry_sync() == set()

    # Externally edited file re-parses.
    (tmp_path / "ext_demo.json").write_text(
        _tool_json("ext_demo", description="edited externally"), encoding="utf-8"
    )
    defn = loader.get_definition("ext_demo")
    assert defn is not None and defn.description == "edited externally"
    assert loader.drain_registry_sync() == {"ext_demo"}

    # Externally deleted file drops the definition.
    (tmp_path / "ext_demo.json").unlink()
    assert loader.get_definition("ext_demo") is None
    assert loader.drain_registry_sync() == {"ext_demo"}


def test_custom_tools_manager_writes_are_not_external_edits(tmp_path):
    from nymeria.tools.definitions.custom_tool_schema import CustomToolDefinition

    loader = _make_loader(tmp_path)
    definition = CustomToolDefinition(**json.loads(_tool_json("mine")))
    loader.save_definition(definition)

    assert loader.refresh_if_stale(force=True) == []
    assert loader.drain_registry_sync() == set()

    assert loader.delete_definition("mine") is True
    assert loader.refresh_if_stale(force=True) == []


def test_mcp_registry_hot_load_add_edit_remove(tmp_path):
    from nymeria.core.mcp_servers import MCPServerRegistry

    registry = MCPServerRegistry(servers_dir=tmp_path)
    registry.EXTERNAL_REFRESH_INTERVAL_SECONDS = 0.0
    assert registry.get_server("srv") is None
    assert registry.drain_registry_sync() is False

    server_json = json.dumps(
        {"id": "srv", "name": "Srv", "transport": "http", "url": "https://example.com"}
    )
    (tmp_path / "srv.json").write_text(server_json, encoding="utf-8")
    defn = registry.get_server("srv")
    assert defn is not None and defn.url == "https://example.com"
    assert registry.drain_registry_sync() is True
    assert registry.drain_registry_sync() is False

    # Different content length: the (mtime_ns, size) fingerprint cannot rely
    # on mtime alone within the kernel's coarse timestamp granularity.
    (tmp_path / "srv.json").write_text(
        server_json.replace("https://example.com", "https://example.org/api"),
        encoding="utf-8",
    )
    defn = registry.get_server("srv")
    assert defn is not None and defn.url == "https://example.org/api"
    assert registry.drain_registry_sync() is True

    (tmp_path / "srv.json").unlink()
    assert registry.get_server("srv") is None
    assert registry.drain_registry_sync() is True


def _write_skill(root, name: str, description: str = "a demo skill", body: str = "Body v1"):
    skill_dir = root / name
    skill_dir.mkdir(parents=True, exist_ok=True)
    (skill_dir / "SKILL.md").write_text(
        f"---\nname: {name}\ndescription: {description}\n---\n\n{body}\n",
        encoding="utf-8",
    )
    return skill_dir


def _make_skill_manager(tmp_path, embedding_index=None):
    from nymeria.skills import SkillManager

    bundled = tmp_path / "bundled"
    data = tmp_path / "data-skills"
    bundled.mkdir()
    manager = SkillManager(bundled, data, embedding_index=embedding_index)
    manager.EXTERNAL_REFRESH_INTERVAL_SECONDS = 0.0
    return manager, data


def test_skills_body_only_edit_hot_loads_via_get(tmp_path):
    manager, data = _make_skill_manager(tmp_path)
    skill_dir = _write_skill(data / "global", "demo-skill")
    manager.reload()
    skill = manager.get("demo-skill")
    assert skill is not None and "Body v1" in skill.body

    # Body-only raw edit: no reload() call anywhere.
    (skill_dir / "SKILL.md").write_text(
        "---\nname: demo-skill\ndescription: a demo skill\n---\n\nBody v2\n",
        encoding="utf-8",
    )
    skill = manager.get("demo-skill")
    assert skill is not None and "Body v2" in skill.body


def test_skills_external_add_and_remove_hot_load(tmp_path):
    manager, data = _make_skill_manager(tmp_path)

    skill_dir = _write_skill(data / "global", "late-skill")
    names = {s.name for s in manager.list_installed()}
    assert "late-skill" in names
    assert manager.get("late-skill") is not None

    import shutil

    shutil.rmtree(skill_dir)
    assert manager.get("late-skill") is None
    assert "late-skill" not in {s.name for s in manager.list_installed()}


def test_skills_corrupt_edit_serves_cached_copy_within_debounce(tmp_path):
    import time as _time

    manager, data = _make_skill_manager(tmp_path)
    skill_dir = _write_skill(data / "global", "fragile-skill")
    manager.reload()
    assert manager.get("fragile-skill") is not None

    # Pin the debounce window open: the scan-level rescan (which drops a
    # no-longer-parsing skill, matching load-time behavior) must not run, so
    # this exercises the per-skill _fresh_skill path serving the cached copy.
    manager.EXTERNAL_REFRESH_INTERVAL_SECONDS = 3600.0
    manager._last_freshness_check = _time.monotonic()

    (skill_dir / "SKILL.md").write_text("no frontmatter at all\n", encoding="utf-8")
    skill = manager.get("fragile-skill")
    assert skill is not None
    assert "Body v1" in skill.body  # cached copy, not the broken file

    # A full rescan drops the no-longer-parsing skill (scan skip behavior).
    manager.reload()
    assert manager.get("fragile-skill") is None


