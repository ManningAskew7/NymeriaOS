    author.add_hook("u1", name="n2", event="done", text="hi2")
    reader.get_hooks_cached("u1")
    assert recorder.records == []  # subsequent manager writes: still no audit

    # Raw on-disk edit. No utime bump: the appended byte changes st_size, and
