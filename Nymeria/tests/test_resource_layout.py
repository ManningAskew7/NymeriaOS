def test_skills_external_edit_triggers_background_index_rebuild(tmp_path):
    import time as _time

    class _FakeIndex:
        def __init__(self):
            self.rebuilds = 0

        def rebuild(self, namespace, items):
            self.rebuilds += 1
            return {"fts_indexed": len(items), "semantic_indexed": 0}

    index = _FakeIndex()
    manager, data = _make_skill_manager(tmp_path, embedding_index=index)
    baseline = index.rebuilds  # init reload() rebuilds inline

    _write_skill(data / "global", "indexed-skill")
    assert manager.refresh_if_stale(force=True) is True

    deadline = _time.monotonic() + 5.0
    while index.rebuilds <= baseline and _time.monotonic() < deadline:
        _time.sleep(0.01)
    assert index.rebuilds > baseline
