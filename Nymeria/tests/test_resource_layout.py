def _env(**overrides) -> ExecutionEnvironment:
    values = dict(
        platform_label="TestOS 1",
        default_cwd="/repo/root",
        process_cwd="/service",
        shell_executable="/bin/sh",
        available_shells=("bash", "sh"),
        in_container=False,
        path_separator="/",
        resource_root="/repo/root/data",
    )
    values.update(overrides)
    return ExecutionEnvironment(**values)


