def _quarantined(store_dir: Path, stem: str) -> list[Path]:
    return list((store_dir / "quarantine").glob(f"{stem}.corrupt-*"))


def test_trigger_store_corrupt_file_is_quarantined_not_overwritten(tmp_path):
    from nymeria.core.trigger_manager import TriggerManager

    manager = TriggerManager(tmp_path)
    path = manager.triggers_dir / "u1.json"
    corrupt = "{ not json"
    path.write_text(corrupt, encoding="utf-8")

    with manager.atomic_update("u1") as store:
        assert store.triggers == []

    assert not path.exists() or path.read_text(encoding="utf-8") != corrupt
    quarantined = _quarantined(manager.triggers_dir, "u1")
    assert len(quarantined) == 1
    assert quarantined[0].read_text(encoding="utf-8") == corrupt


