class _AuditRecorder:
    def __init__(self):
        self.records = []

    def __call__(self, store, detail, *, user_id="default"):
        self.records.append((store, detail, user_id))


def test_store_fingerprint_sidecar_roundtrip(tmp_path):
    from nymeria.core.storage_paths import (
        read_store_fingerprint,
        record_store_fingerprint,
        store_fingerprint_path,
    )

    target = tmp_path / "store.json"
    assert read_store_fingerprint(target) is None  # absent sidecar: fail-safe
    target.write_text("{}", encoding="utf-8")
    sig = record_store_fingerprint(target)
    st = target.stat()
    assert sig == (st.st_mtime_ns, st.st_size)
    assert read_store_fingerprint(target) == sig

    # A corrupt sidecar reads as None instead of raising.
    store_fingerprint_path(target).write_text("not-a-sig", encoding="utf-8")
    assert read_store_fingerprint(target) is None

    # Recording for a missing store drops the stale sidecar.
    record_store_fingerprint(target)
    target.unlink()
    assert record_store_fingerprint(target) is None
    assert not store_fingerprint_path(target).exists()


def test_hooks_external_edit_is_audited_user_attributed(tmp_path, monkeypatch):
    """Cross-instance: authoring writes via its own manager (the tools/REST
    singletons in production), the engine reads via a separate instance. The
    shared .sig sidecar is what lets the reader tell manager writes from raw
    on-disk edits."""
    from nymeria.core.hook_manager import HookManager

    recorder = _AuditRecorder()
    monkeypatch.setattr("nymeria.core.activity_log.log_external_edit", recorder)

    author = HookManager(tmp_path)  # the tools/REST authoring instance
    reader = HookManager(tmp_path)  # the engine instance (never saves)
    author.add_hook("u1", name="n", event="done", text="hi")
    reader.get_hooks_cached("u1")
    assert recorder.records == []  # cross-instance manager write: no audit

    author.add_hook("u1", name="n2", event="done", text="hi2")
    reader.get_hooks_cached("u1")
    assert recorder.records == []  # subsequent manager writes: still no audit

    # Raw on-disk edit. No utime bump: the appended byte changes st_size, and
    # size is part of both the read-cache key and the fingerprint, so the
    # edit is seen even when the kernel's coarse timestamp clock gives it the
    # same mtime_ns as the manager save.
    path = reader._path_for("u1")
    path.write_text(path.read_text(encoding="utf-8") + "\n", encoding="utf-8")
    reader.get_hooks_cached("u1")
    assert ("hooks", "hook store file edited on disk", "u1") in recorder.records

    # Acknowledged in the shared sidecar: audited once, across instances.
    count = len(recorder.records)
    reader.get_hooks_cached("u1")
    HookManager(tmp_path).get_hooks_cached("u1")
    assert len(recorder.records) == count


def test_triggers_external_edit_is_audited_once(tmp_path, monkeypatch):
    """Cross-instance: fire-state saves happen in the ticker's manager (a
    separate process in the Docker shape) while authoring goes through the
    tool/REST managers. Neither side's saves may audit as external."""
    from nymeria.core.trigger_manager import TriggerManager, TriggerStore

    recorder = _AuditRecorder()
    monkeypatch.setattr("nymeria.core.activity_log.log_external_edit", recorder)

    ticker_side = TriggerManager(tmp_path)  # the ticker's instance
    authoring = TriggerManager(tmp_path)  # the tool/REST authoring instance
    ticker_side._save(TriggerStore(user_id="u1"))
    authoring._load("u1")
    assert recorder.records == []  # cross-instance manager write: no audit

    authoring._save(TriggerStore(user_id="u1"))
    ticker_side._load("u1")
    assert recorder.records == []  # and in the other direction

    path = ticker_side.triggers_dir / "u1.json"
    path.write_text(path.read_text(encoding="utf-8") + "\n", encoding="utf-8")
    ticker_side._load("u1")
    assert ("triggers", "trigger store file edited on disk", "u1") in recorder.records

    # Acknowledged in the shared sidecar: once, not per poll or per instance.
    count = len(recorder.records)
    ticker_side._load("u1")
    authoring._load("u1")
    assert len(recorder.records) == count


