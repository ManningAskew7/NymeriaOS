def test_tool_config_hash_ignores_catalog():
    # tool_config_hash hashes the ThreadConfig slice (user_id, thread_id,
    # enabled/disabled/temporary tools, enabled/disabled skills). It never
    # reads CATALOG_TOOLS, so catalog assembly cannot move the prompt-cache
    # prefix. We call it via the module function with agent=None because the
    # implementation does not touch `agent` for a plain config.
    from nymeria.core import agent_graph

    class _TC:
        enabled_tools = ["bash_execute"]
        disabled_tools = ["file_write"]
        temporary_tools = {}
        enabled_skills = []
        disabled_skills = []

    h1 = agent_graph.tool_config_hash(None, "u1", "t1", _TC())
    h2 = agent_graph.tool_config_hash(None, "u1", "t1", _TC())
    assert h1 == h2
    # A None config hashes to the empty-slice digest, also catalog-independent.
    assert agent_graph.tool_config_hash(None, "u1", "t1", None) == agent_graph.tool_config_hash(
        None, "u1", "t1", None
    )


