def test_static_tool_catalog_is_seed_union_catalog():
    # static_tool_catalog() is exactly SEED_TOOLS merged with CATALOG_TOOLS,
    # and the two are disjoint (seed tools are never catalog tools).
    seed_map = {t.name: t for t in T.SEED_TOOLS}
    merged = dict(seed_map)
    merged.update(T.CATALOG_TOOLS)
    static = T.static_tool_catalog()
    assert static.keys() == merged.keys()
    for name in static:
        assert static[name] is merged[name]
    assert set(seed_map) & set(T.CATALOG_TOOLS) == set()


