"""Golden tests for the auto-discovered tool catalog (backlog #51, Workstream A).

These tests pin the catalog-assembly refactor to be BYTE-IDENTICAL in the only
sense that matters at runtime: the name->tool MAPPING, the role-gate sets, the
seed set, and the tool counts. They passed against the pre-refactor
hand-maintained comprehension and must keep passing after each family migrates
to ``register_tool_group``.

The baseline name sets below were snapshotted from ``main`` BEFORE the registry
refactor (catalog 1258 tools, static seed+catalog 1273 tools). Assembly moved
from a hand-listed union to a registry-derived one; resolution
(``select_tools_for_graph`` / ``compute_tool_superset`` /
``static_tool_catalog``) is untouched, so if the mapping matches the snapshot,
every downstream consumer is unaffected.

Prompt-cache note (do not fear a cache regression): the dynamic-binding cache
key is ``agent_graph.tool_config_hash``, which hashes ONLY the per-thread
ThreadConfig slice (enabled/disabled/temporary tools + enabled/disabled
skills), never the catalog. Catalog assembly therefore cannot change the
request prefix or the Anthropic prompt-cache prefix. ``test_tool_config_hash_*``
below asserts the hash ignores the catalog.
"""

